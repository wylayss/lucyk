static volatile int fbcon_released; /* atomic handover flag */
static spinlock_t fbcon_lock; /* IRQ-safe output serialization */

struct fbcon_state {
    volatile uint8_t *fb;
    uint32_t width, height, pitch, bpp;
    uint8_t rms, rsh, gms, gsh, bms, bsh;
    uint32_t bytes_per_pixel;
    uint32_t cols, rows;
    uint32_t cx, cy;      /* cell cursor */
    uint32_t fg, bg;
    bool active;
};

static struct fbcon_state fb;

static uint32_t pack_pixel(uint8_t r, uint8_t g, uint8_t b)
{
    uint32_t px = 0;

    if (fb.rms != 0) {
        uint32_t maxv = (fb.rms >= 32U) ? 0xFFFFFFFFU : ((1U << fb.rms) - 1U);
        px |= ((r * maxv + 127U) / 255U) << fb.rsh;
    }
    if (fb.gms != 0) {
        uint32_t maxv = (fb.gms >= 32U) ? 0xFFFFFFFFU : ((1U << fb.gms) - 1U);
        px |= ((g * maxv + 127U) / 255U) << fb.gsh;
    }
    if (fb.bms != 0) {
        uint32_t maxv = (fb.bms >= 32U) ? 0xFFFFFFFFU : ((1U << fb.bms) - 1U);
        px |= ((b * maxv + 127U) / 255U) << fb.bsh;
    }
    return px;
}

static void put_pixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= fb.width || y >= fb.height || fb.fb == NULL) {
        return;
    }

    uint8_t *row = (uint8_t *)fb.fb + (uint64_t)y * fb.pitch + (uint64_t)x * fb.bytes_per_pixel;

    switch (fb.bytes_per_pixel) {
    case 4:
        row[0] = (uint8_t)(color & 0xFFU);
        row[1] = (uint8_t)((color >> 8) & 0xFFU);
        row[2] = (uint8_t)((color >> 16) & 0xFFU);
        row[3] = (uint8_t)((color >> 24) & 0xFFU);
        break;
    case 3:
        row[0] = (uint8_t)(color & 0xFFU);
        row[1] = (uint8_t)((color >> 8) & 0xFFU);
        row[2] = (uint8_t)((color >> 16) & 0xFFU);
        break;
    case 2:
        row[0] = (uint8_t)(color & 0xFFU);
        row[1] = (uint8_t)((color >> 8) & 0xFFU);
        break;
    case 1:
        row[0] = (uint8_t)(color & 0xFFU);
        break;
    default:
        break;
    }
}

static void draw_cell(uint32_t col, uint32_t row, uint8_t ch)
{
    const uint8_t *glyph = font8x16_fallback;

    if (ch >= FBCON_GLYPH_FIRST && ch <= FBCON_GLYPH_LAST) {
        glyph = font8x16[ch - FBCON_GLYPH_FIRST];
    }

    uint32_t px0 = col * FBCON_GLYPH_W;
    uint32_t py0 = row * FBCON_GLYPH_H;

    for (uint32_t gy = 0; gy < FBCON_GLYPH_H; gy++) {
        uint8_t bits = glyph[gy];
        for (uint32_t gx = 0; gx < FBCON_GLYPH_W; gx++) {
            uint32_t color = (bits & (0x80U >> gx)) ? fb.fg : fb.bg;
            put_pixel(px0 + gx, py0 + gy, color);
        }
    }
}

static void clear_cell(uint32_t col, uint32_t row);

static void scroll_up(void)
{
    if (fb.fb == NULL) {
        return;
    }

    uint32_t line_bytes = fb.pitch;
    uint8_t *dst = (uint8_t *)fb.fb;
    const uint8_t *src = dst + (uint64_t)FBCON_GLYPH_H * line_bytes;
    uint32_t move_lines = (fb.rows - 1U) * FBCON_GLYPH_H;

    /* Overlapping copy downwards. */
    for (uint32_t y = 0; y < move_lines; y++) {
        memcpy(dst + (uint64_t)y * line_bytes, src + (uint64_t)y * line_bytes,
               fb.width * fb.bytes_per_pixel);
    }

    /* Clear the last cell row. */
    for (uint32_t col = 0; col < fb.cols; col++) {
        clear_cell(col, fb.rows - 1U);
    }
}

static void clear_cell(uint32_t col, uint32_t row)
{
    uint32_t px0 = col * FBCON_GLYPH_W;
    uint32_t py0 = row * FBCON_GLYPH_H;

    for (uint32_t gy = 0; gy < FBCON_GLYPH_H; gy++) {
        for (uint32_t gx = 0; gx < FBCON_GLYPH_W; gx++) {
            put_pixel(px0 + gx, py0 + gy, fb.bg);
        }
    }
}

void fbcon_init(void *addr, uint32_t width, uint32_t height, uint32_t pitch,
                uint32_t bpp, uint8_t red_mask_size, uint8_t red_shift,
                uint8_t green_mask_size, uint8_t green_shift,
                uint8_t blue_mask_size, uint8_t blue_shift)
{
    fbcon_released = 0;
    spinlock_init(&fbcon_lock);

    if (addr == NULL || width < FBCON_GLYPH_W || height < FBCON_GLYPH_H ||
        pitch == 0 || (bpp != 32U && bpp != 24U && bpp != 16U && bpp != 8U)) {
        fb.active = false;
        return;
    }

    fb.fb = (volatile uint8_t *)addr;
    fb.width = width;
    fb.height = height;
    fb.pitch = pitch;
    fb.bpp = bpp;
    fb.bytes_per_pixel = bpp / 8U;
    fb.rms = red_mask_size;
    fb.rsh = red_shift;
    fb.gms = green_mask_size;
    fb.gsh = green_shift;
    fb.bms = blue_mask_size;
    fb.bsh = blue_shift;
    fb.cols = width / FBCON_GLYPH_W;
    fb.rows = height / FBCON_GLYPH_H;
    fb.cx = 0;
    fb.cy = 0;
    fb.fg = pack_pixel(0xCC, 0xCC, 0xCC);
    fb.bg = pack_pixel(0x00, 0x00, 0x00);
    fb.active = true;
}

void fbcon_release(void)
{
    /* Atomic handover under the output lock; no partial draws after this
     * point, no CPU can emit a stale pixel once release() returns. */
    uint64_t flags = spin_lock_irqsave(&fbcon_lock);
    __atomic_store_n(&fbcon_released, 1, __ATOMIC_RELEASE);
    fb.active = false;
    spin_unlock_irqrestore(&fbcon_lock, flags);
}

bool fbcon_active(void)
{
    return fb.active && !__atomic_load_n(&fbcon_released, __ATOMIC_ACQUIRE);
}

static void fbcon_putc_locked(char c)
{
    if (c == '\n') {
        fb.cx = 0;
        if (fb.cy + 1U >= fb.rows) {
            scroll_up();
        } else {
            fb.cy++;
        }
        return;
    }
    if (c == '\r') {
        fb.cx = 0;
        return;
    }
    if (c == '\b') {
        if (fb.cx > 0) {
            fb.cx--;
        } else if (fb.cy > 0) {
            fb.cy--;
            fb.cx = fb.cols ? fb.cols - 1U : 0;
        }
        clear_cell(fb.cx, fb.cy);
        return;
    }
    if (c == '\t') {
        uint32_t next = (fb.cx + FBCON_TAB_WIDTH) & ~(FBCON_TAB_WIDTH - 1U);
        if (next >= fb.cols) {
            next = fb.cols ? fb.cols - 1U : 0;
        }
        while (fb.cx < next) {
            clear_cell(fb.cx, fb.cy);
            fb.cx++;
        }
        return;
    }

    draw_cell(fb.cx, fb.cy, (uint8_t)c);
    fb.cx++;
    if (fb.cx >= fb.cols) {
        fb.cx = 0;
        if (fb.cy + 1U >= fb.rows) {
            scroll_up();
        } else {
            fb.cy++;
        }
    }
}

void fbcon_putc(char c)
{
    uint64_t flags = spin_lock_irqsave(&fbcon_lock);

    if (fbcon_active() && fb.fb != NULL) {
        fbcon_putc_locked(c);
    }

    spin_unlock_irqrestore(&fbcon_lock, flags);
}

void fbcon_write(const char *s, size_t len)
{
    /* Serialize the whole burst; avoid recursion on fbcon_putc. */
    uint64_t flags = spin_lock_irqsave(&fbcon_lock);

    if (fbcon_active()) {
        for (size_t i = 0; i < len; i++) {
            fbcon_putc_locked(s[i]);
        }
    }

    spin_unlock_irqrestore(&fbcon_lock, flags);
}
