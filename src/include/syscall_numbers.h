#ifndef LUCYK_SYSCALL_NUMBERS_H
#define LUCYK_SYSCALL_NUMBERS_H

/* Native microkernel syscall numbers (bit 63 set). */
#define SYS_THREAD_EXIT    0x8000000000000001ULL
#define SYS_THREAD_YIELD   0x8000000000000002ULL
#define SYS_THREAD_SLEEP_MS 0x8000000000000003ULL
#define SYS_THREAD_SET_QOS 0x8000000000000004ULL
#define SYS_TASK_ID        0x8000000000000005ULL
#define SYS_IPC_CALL       0x8000000000000010ULL
#define SYS_IPC_RECV       0x8000000000000011ULL
#define SYS_IPC_REPLY      0x8000000000000012ULL
#define SYS_ENDPOINT_CREATE 0x8000000000000013ULL
#define SYS_NOTIFY_SIGNAL  0x8000000000000020ULL
#define SYS_NOTIFY_WAIT    0x8000000000000021ULL
#define SYS_NOTIFY_CREATE  0x8000000000000022ULL
#define SYS_CAP_DERIVE     0x8000000000000030ULL
#define SYS_CAP_GRANT      0x8000000000000031ULL
#define SYS_CAP_DELETE     0x8000000000000032ULL
#define SYS_VSPACE_MAP     0x8000000000000040ULL
#define SYS_VSPACE_UNMAP   0x8000000000000041ULL
#define SYS_IRQ_BIND       0x8000000000000050ULL
#define SYS_IRQ_ACK        0x8000000000000051ULL
#define SYS_DEBUG_LOG      0x80000000000000F0ULL

/* SYS_THREAD_SET_QOS classes (identical to THREAD_QOS_* in task.h). Passing
 * SYS_QOS_QUERY leaves the thread unchanged and only reports its classes. */
#define SYS_QOS_BACKGROUND  0ULL
#define SYS_QOS_DEFAULT     1ULL
#define SYS_QOS_INTERACTIVE 2ULL
#define SYS_QOS_QUERY       0xFFFFFFFFFFFFFFFFULL

/* SYS_CAP_GRANT target selector naming the calling task itself. */
#define SYS_CAP_GRANT_SELF  0ULL

#endif /* LUCYK_SYSCALL_NUMBERS_H */
